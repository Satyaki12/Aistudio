import type { BuildConfig, GeneratedFile } from './types.ts';

/**
 * Generates a complete, turnkey Progressive Web App (PWA) package.
 * Requires ZERO Android Studio, zero Java/Kotlin compilation, and installs
 * directly on Android, iOS, Windows, macOS, and ChromeOS via browser native Add to Home Screen.
 */
export function generatePwaPackage(config: BuildConfig): {
  files: GeneratedFile[];
  previews: Record<string, string>;
  snippet: string;
  readme: string;
} {
  const files: GeneratedFile[] = [];

  // Safe short name: <= 12 characters to prevent truncation on mobile home screens
  const safeShortName = (config.appName || 'WebApp').replace(/[^a-zA-Z0-9]/g, '').slice(0, 12) || 'WebApp';

  // 1. Web App Manifest (manifest.webmanifest)
  const manifestJson = {
    id: '/',
    name: config.appName,
    short_name: safeShortName,
    description: `Official Progressive Web App for ${config.appName}. Installable on mobile and desktop without app store or Android Studio.`,
    start_url: '/',
    scope: '/',
    display: config.isFullScreen ? 'fullscreen' : 'standalone',
    orientation: config.orientation === 'unspecified' ? 'any' : config.orientation,
    background_color: config.splashColor || '#0b0f19',
    theme_color: config.primaryColor || '#4F46E5',
    categories: ['utilities', 'business', 'lifestyle'],
    icons: [
      {
        src: '/icons/icon-192.png',
        sizes: '192x192',
        type: 'image/png',
        purpose: 'any'
      },
      {
        src: '/icons/icon-512.png',
        sizes: '512x512',
        type: 'image/png',
        purpose: 'any'
      },
      {
        src: '/icons/icon-maskable-512.png',
        sizes: '512x512',
        type: 'image/png',
        purpose: 'maskable'
      }
    ],
    shortcuts: [
      {
        name: 'Home',
        short_name: 'Home',
        url: '/',
        icons: [{ src: '/icons/icon-192.png', sizes: '192x192' }]
      }
    ]
  };

  const manifestContent = JSON.stringify(manifestJson, null, 2);
  files.push({ path: 'manifest.webmanifest', content: manifestContent });
  files.push({ path: 'manifest.json', content: manifestContent });

  // 2. Production Service Worker (sw.js)
  const swJs = `// Progressive Web App Service Worker
// Generated by URL2PWA for ${config.appName}
const CACHE_NAME = '${safeShortName.toLowerCase()}-pwa-v${config.versionName || '1.0.0'}';
const OFFLINE_URL = '/offline.html';

const PRECACHE_ASSETS = [
  '/',
  '/offline.html',
  '/manifest.webmanifest',
  '/icons/icon-192.png',
  '/icons/icon-512.png',
  '/icons/icon-maskable-512.png'
];

// Install: precache offline fallback and essential assets
self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(PRECACHE_ASSETS).catch((err) => {
        console.warn('Precache partial fallback:', err);
      });
    }).then(() => self.skipWaiting())
  );
});

// Activate: clean up outdated version caches
self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((cacheNames) => {
      return Promise.all(
        cacheNames.map((name) => {
          if (name !== CACHE_NAME) {
            return caches.delete(name);
          }
        })
      );
    }).then(() => self.clients.claim())
  );
});

// Fetch: Network-first for HTML pages with offline fallback; Cache-first for images/fonts
self.addEventListener('fetch', (event) => {
  const req = event.request;

  // Ignore non-GET or chrome-extension requests
  if (req.method !== 'GET' || !req.url.startsWith('http')) {
    return;
  }

  // HTML Navigation requests: Network-first with offline fallback
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req).catch(async () => {
        const cache = await caches.open(CACHE_NAME);
        const cachedOffline = await cache.match(OFFLINE_URL);
        return cachedOffline || new Response('Offline - No connection available', {
          headers: { 'Content-Type': 'text/plain' }
        });
      })
    );
    return;
  }

  // Static Assets (CSS, JS, Fonts, Images): Stale-While-Revalidate
  event.respondWith(
    caches.match(req).then((cachedResponse) => {
      const fetchPromise = fetch(req).then((networkResponse) => {
        if (networkResponse && networkResponse.status === 200) {
          const responseClone = networkResponse.clone();
          caches.open(CACHE_NAME).then((cache) => {
            cache.put(req, responseClone);
          });
        }
        return networkResponse;
      }).catch(() => cachedResponse);

      return cachedResponse || fetchPromise;
    })
  );
});
`;
  files.push({ path: 'sw.js', content: swJs });

  // 3. Branded Standalone Offline Page (offline.html)
  const offlineHtml = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${config.appName} - Offline</title>
  <style>
    :root {
      --primary: ${config.primaryColor || '#4F46E5'};
      --bg: ${config.splashColor || '#0b0f19'};
    }
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body {
      background-color: var(--bg);
      color: #f1f5f9;
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
      min-height: 100vh;
      display: flex;
      flex-direction: column;
      align-items: center;
      justify-content: center;
      padding: 24px;
      text-align: center;
    }
    .card {
      max-width: 420px;
      width: 100%;
      background: rgba(30, 41, 59, 0.7);
      border: 1px solid rgba(255, 255, 255, 0.1);
      border-radius: 24px;
      padding: 36px 24px;
      backdrop-filter: blur(10px);
      box-shadow: 0 20px 40px rgba(0,0,0,0.4);
    }
    .icon-box {
      width: 72px;
      height: 72px;
      border-radius: 20px;
      background: var(--primary);
      display: inline-flex;
      align-items: center;
      justify-content: center;
      font-size: 28px;
      font-weight: 800;
      color: #fff;
      margin-bottom: 20px;
      box-shadow: 0 8px 16px rgba(0,0,0,0.3);
    }
    h1 { font-size: 20px; font-weight: 700; margin-bottom: 8px; }
    p { font-size: 14px; color: #94a3b8; line-height: 1.5; margin-bottom: 24px; }
    .btn {
      display: inline-block;
      width: 100%;
      background: var(--primary);
      color: #fff;
      font-weight: 600;
      font-size: 14px;
      padding: 12px 20px;
      border-radius: 12px;
      border: none;
      cursor: pointer;
      text-decoration: none;
      transition: opacity 0.2s;
    }
    .btn:hover { opacity: 0.9; }
    .btn:active { transform: scale(0.98); }
    .status {
      margin-top: 16px;
      font-size: 12px;
      color: #64748b;
    }
  </style>
</head>
<body>
  <div class="card">
    <div class="icon-box">${(config.appName.charAt(0) || 'A').toUpperCase()}</div>
    <h1>You are currently offline</h1>
    <p>Please check your internet connection. We will automatically reconnect as soon as signal returns.</p>
    <button class="btn" onclick="window.location.reload()">Retry Connection</button>
    <div class="status" id="status">Monitoring network connection…</div>
  </div>

  <script>
    window.addEventListener('online', () => {
      document.getElementById('status').innerText = 'Connection restored! Reloading…';
      setTimeout(() => window.location.reload(), 800);
    });
  </script>
</body>
</html>
`;
  files.push({ path: 'offline.html', content: offlineHtml });

  // 4. Copy-paste snippet for any website HTML head (pwa-snippet.html)
  const snippet = `<!-- Progressive Web App Head Tags for ${config.appName} -->
<meta name="theme-color" content="${config.primaryColor || '#4F46E5'}">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="${safeShortName}">

<link rel="manifest" href="/manifest.webmanifest">
<link rel="apple-touch-icon" href="/icons/apple-touch-icon.png">
<link rel="icon" type="image/png" sizes="192x192" href="/icons/icon-192.png">

<!-- Service Worker Registration -->
<script>
  if ('serviceWorker' in navigator) {
    window.addEventListener('load', () => {
      navigator.serviceWorker.register('/sw.js')
        .then(reg => console.log('PWA Service Worker registered:', reg.scope))
        .catch(err => console.error('PWA Registration failed:', err));
    });
  }
</script>
`;
  files.push({ path: 'pwa-head-snippet.html', content: snippet });

  // 5. SVG Icon representation
  const iconSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512" width="512" height="512">
  <rect width="512" height="512" rx="128" fill="${config.primaryColor || '#4F46E5'}" />
  <text x="50%" y="54%" dominant-baseline="middle" text-anchor="middle" font-family="-apple-system, system-ui, sans-serif" font-weight="800" font-size="240" fill="#ffffff">
    ${(config.appName.charAt(0) || 'A').toUpperCase()}
  </text>
</svg>`;
  files.push({ path: 'icons/icon.svg', content: iconSvg });

  // 6. Comprehensive Deployment Readme (README-PWA.md)
  const readme = `# ${config.appName} - Progressive Web App (PWA)

Generated by **URL2PWA**.

### 🌟 Why PWA?
- **Zero Android Studio**: No SDK downloads, no Gradle builds, no Java setup.
- **Universal**: Installs instantly on Android, iOS (iPhone/iPad), macOS, Windows, and ChromeOS.
- **App-like Experience**: Runs full-screen with no browser address bar or tabs.
- **Offline Capable**: Includes service worker with offline fallback page.

---

## 🚀 How to Install on Your Website (3 Steps)

### Step 1: Copy Files to Your Website Root
Upload the following files to the public root directory of your website (e.g. \`public_html\`, \`public/\`, or \`www/\`):
- \`manifest.webmanifest\`
- \`sw.js\`
- \`offline.html\`
- \`icons/\` directory

### Step 2: Add Head Snippet
Paste the contents of \`pwa-head-snippet.html\` into your website's \`<head>\` section:

\`\`\`html
<meta name="theme-color" content="${config.primaryColor || '#4F46E5'}">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<link rel="manifest" href="/manifest.webmanifest">
<link rel="apple-touch-icon" href="/icons/apple-touch-icon.png">
<script>
  if ('serviceWorker' in navigator) {
    navigator.serviceWorker.register('/sw.js');
  }
</script>
\`\`\`

---

## 📱 How Users Install It (Zero App Store Required)

- **Android (Chrome / Samsung Internet)**:
  When users visit your site, the browser automatically displays an **"Install App"** prompt, or they can tap **⋮ (Menu) > "Install app"**.
  
- **iPhone / iPad (Safari)**:
  Users tap the **Share** button in Safari, then tap **"Add to Home Screen"**. It launches with its own icon and full-screen window without Safari chrome!

- **Desktop (Windows / Mac / ChromeOS)**:
  An install icon (🖥️) appears in the Chrome/Edge address bar. Clicking it installs your site as a standalone desktop app with desktop shortcut and taskbar icon!
`;
  files.push({ path: 'README-PWA.md', content: readme });

  const previews: Record<string, string> = {
    'manifest.webmanifest': manifestContent,
    'sw.js': swJs,
    'offline.html': offlineHtml,
    'pwa-head-snippet.html': snippet,
    'README-PWA.md': readme
  };

  return {
    files,
    previews,
    snippet,
    readme
  };
}
